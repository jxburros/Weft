import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

export function renderTokens(tokens) {
  const declarations = (values) => Object.entries(values).map(([name, value]) => `  --${name}: ${value};`).join("\n");
  return `/* Generated by node scripts/generate-tokens.js. Edit tokens.json. */\n:root {\n${declarations({...tokens.common, ...tokens.themes.light})}\n  color-scheme: light;\n}\n:root[data-theme="dark"] {\n${declarations(tokens.themes.dark)}\n  color-scheme: dark;\n}\n@media (prefers-reduced-motion: reduce) {\n  :root {\n${declarations(tokens.reducedMotion).split("\n").map(line => `  ${line}`).join("\n")}\n  }\n}\n`;
}
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(new URL("../assets/tokens.css", import.meta.url), renderTokens(JSON.parse(readFileSync(new URL("../assets/tokens.json", import.meta.url), "utf8"))));
}
